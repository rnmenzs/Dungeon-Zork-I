#include <locale.h>
#include <windows.h>
#include <ctype.h>
#include "./headers/events.h"

void initialBanner();

extern int battle;

int main()
{

    srand(time(NULL));
    setlocale(LC_ALL, "Portuguese");

    battle = 0;
    jogador.alive = 1;
    jogador.hp = 20;
    jogador.CA = 10;

    char comando[50];

    system("cls");

    initialBanner();

    system("pause");

    printf("\nDigite seu nickname: ");
    gets(jogador.name);

    while (jogador.alive == 1)
    {
        printf("\nDigite o comando: ");

        if (battle == 1)
        {
            combat();
            
        }
        else
        {
            getCommand(comando);
            defaultCommandValidator(comando);
            statusBar(jogador);
        }
    }

    if (jogador.alive == 0)
    {
        printf("\x1b[2;31;40m---------You Died----------\x1b[0m\n");
    }

    return 0;
}

